"""Generates the IAM role templates (FR-4) from policies/afinin-readonly.json,
the single source of truth for the permissions Afinín needs.

Run after editing the policy; CI fails if the generated files are stale.
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
POLICY = json.loads((ROOT / "policies/afinin-readonly.json").read_text())
HEADER = "Generated by scripts/generate-policy-templates.py from policies/afinin-readonly.json. Do not edit."


def yaml_list(items, indent):
    pad = " " * indent
    return "\n".join(f"{pad}- {json.dumps(i)}" for i in items)


def cloudformation():
    statements = []
    for st in POLICY["Statement"]:
        statements.append(
            f"""              - Sid: {st['Sid']}
                Effect: {st['Effect']}
                Action:
{yaml_list(st['Action'], 18)}
                Resource: {json.dumps(st['Resource'])}"""
        )
    return f"""# SPDX-License-Identifier: MIT OR Apache-2.0
# {HEADER}
#
# Read-only role for Afinín. Deploy to one account, or to every account in an
# AWS Organization as a CloudFormation StackSet:
#
#   aws cloudformation create-stack-set --stack-set-name afinin-readonly \\
#     --template-body file://afinin-readonly-role.yaml \\
#     --permission-model SERVICE_MANAGED --auto-deployment Enabled=true,RetainStacksOnAccountRemoval=false \\
#     --capabilities CAPABILITY_NAMED_IAM \\
#     --parameters ParameterKey=TrustedPrincipalArn,ParameterValue=<arn>
#   aws cloudformation create-stack-instances --stack-set-name afinin-readonly \\
#     --deployment-targets OrganizationalUnitIds=<root-or-ou-id> --regions us-east-1
AWSTemplateFormatVersion: "2010-09-09"
Description: Read-only IAM role assumed by Afinín (never mutates resources).

Parameters:
  TrustedPrincipalArn:
    Type: String
    Description: >-
      Who may assume the role, e.g. the IAM Identity Center role or the management
      account root (arn:aws:iam::<management-account-id>:root).
  RoleName:
    Type: String
    Default: AfininReadOnly
  ExternalId:
    Type: String
    Default: ""
    Description: Optional external ID required when assuming the role.

Conditions:
  HasExternalId: !Not [!Equals [!Ref ExternalId, ""]]

Resources:
  Role:
    Type: AWS::IAM::Role
    Properties:
      RoleName: !Ref RoleName
      Description: Read-only access for Afinín cost and inventory analysis
      MaxSessionDuration: 3600
      AssumeRolePolicyDocument:
        Version: "2012-10-17"
        Statement:
          - Effect: Allow
            Principal:
              AWS: !Ref TrustedPrincipalArn
            Action: sts:AssumeRole
            Condition: !If
              - HasExternalId
              - StringEquals:
                  sts:ExternalId: !Ref ExternalId
              - !Ref AWS::NoValue
      Policies:
        - PolicyName: afinin-readonly
          PolicyDocument:
            Version: "2012-10-17"
            Statement:
{chr(10).join(statements)}

Outputs:
  RoleArn:
    Value: !GetAtt Role.Arn
"""


def terraform():
    return {
        "main.tf": f"""# SPDX-License-Identifier: MIT OR Apache-2.0
# {HEADER}

data "aws_iam_policy_document" "trust" {{
  statement {{
    effect  = "Allow"
    actions = ["sts:AssumeRole"]
    principals {{
      type        = "AWS"
      identifiers = var.trusted_principal_arns
    }}
    dynamic "condition" {{
      for_each = var.external_id == null ? [] : [var.external_id]
      content {{
        test     = "StringEquals"
        variable = "sts:ExternalId"
        values   = [condition.value]
      }}
    }}
  }}
}}

resource "aws_iam_role" "afinin" {{
  name                 = var.role_name
  description          = "Read-only access for Afinin cost and inventory analysis"
  assume_role_policy   = data.aws_iam_policy_document.trust.json
  max_session_duration = 3600
  tags                 = var.tags
}}

resource "aws_iam_role_policy" "afinin" {{
  name   = "afinin-readonly"
  role   = aws_iam_role.afinin.id
  policy = file("${{path.module}}/policy.json")
}}
""",
        "variables.tf": """# SPDX-License-Identifier: MIT OR Apache-2.0

variable "trusted_principal_arns" {
  description = "Principals allowed to assume the role (IAM Identity Center role, management account root…)."
  type        = list(string)
}

variable "role_name" {
  description = "Name of the read-only role."
  type        = string
  default     = "AfininReadOnly"
}

variable "external_id" {
  description = "Optional external ID required to assume the role."
  type        = string
  default     = null
}

variable "tags" {
  description = "Tags for the role."
  type        = map(string)
  default     = {}
}
""",
        "outputs.tf": """# SPDX-License-Identifier: MIT OR Apache-2.0

output "role_arn" {
  description = "ARN of the role to put in the AWS profile Afinin uses (role_arn)."
  value       = aws_iam_role.afinin.arn
}
""",
        "versions.tf": """# SPDX-License-Identifier: MIT OR Apache-2.0

terraform {
  required_version = ">= 1.3"
  required_providers {
    aws = {
      source  = "hashicorp/aws"
      version = ">= 5.0"
    }
  }
}
""",
        "policy.json": json.dumps(POLICY, indent=2) + "\n",
    }


(ROOT / "policies/cloudformation/afinin-readonly-role.yaml").write_text(cloudformation())
for name, content in terraform().items():
    (ROOT / "policies/terraform/afinin-readonly-role" / name).write_text(content)
print("policy templates generated")
